-- Private tables. The server uses a secret key; browsers never access these tables directly.
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  sku text not null default '',
  name text not null,
  uom text not null default 'pc',
  cost numeric not null check (cost >= 0),
  supplier text not null default '',
  source_url text not null default ''
);
create table if not exists public.quotations (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  company text not null default '',
  contact text not null default '',
  total numeric not null default 0,
  item_count integer not null default 0,
  details jsonb not null default '{}'::jsonb
);
alter table public.products enable row level security;
alter table public.quotations enable row level security;
-- No anonymous or authenticated RLS policies: access only through server-side service-role key.
revoke all on table public.products, public.quotations from anon, authenticated;
grant all on table public.products, public.quotations to service_role;
grant usage, select on sequence public.products_id_seq, public.quotations_id_seq to service_role;
